// Client-side PDF generation for receipts/invoices using jsPDF.
import { jsPDF } from 'jspdf';

export function downloadReceiptPdf(doc: {
  kind?: string;
  code?: string;
  number?: string;
  buyerName?: string;
  buyerPhone?: string;
  items?: Array<{ name: string; qty?: number; unit?: number; price?: number }>;
  total?: number;
  totalKes?: number;
  paymentRef?: string;
  mpesaCode?: string;
  createdAt?: string;
  businessName?: string;
  ownerName?: string;
}) {
  const pdf = new jsPDF({ unit: 'mm', format: 'a4' });
  const kind = (doc.kind || 'receipt').toUpperCase();
  const code = doc.code || doc.number || '';
  const total = doc.total ?? doc.totalKes ?? 0;
  const items = doc.items || [];
  const biz = doc.businessName || 'PlugPay Seller';
  const owner = doc.ownerName || '';
  const ref = doc.paymentRef || doc.mpesaCode || '';

  let y = 18;
  pdf.setFontSize(18);
  pdf.setFont('helvetica', 'bold');
  pdf.text(biz, 14, y);
  y += 7;
  if (owner) { pdf.setFontSize(10); pdf.setFont('helvetica', 'normal'); pdf.text(owner, 14, y); y += 6; }

  pdf.setFontSize(14);
  pdf.setFont('helvetica', 'bold');
  pdf.text(kind === 'INVOICE' ? 'INVOICE' : 'RECEIPT', 14, y);
  y += 6;
  pdf.setFontSize(10);
  pdf.setFont('helvetica', 'normal');
  pdf.text(`No: ${code}`, 14, y); y += 5;
  if (doc.createdAt) { pdf.text(`Date: ${new Date(doc.createdAt).toLocaleString()}`, 14, y); y += 5; }
  if (doc.buyerName) { pdf.text(`Buyer: ${doc.buyerName}`, 14, y); y += 5; }
  if (doc.buyerPhone) { pdf.text(`Phone: ${doc.buyerPhone}`, 14, y); y += 5; }
  if (ref) { pdf.text(`M-Pesa: ${ref}`, 14, y); y += 6; }

  // items table
  pdf.setFont('helvetica', 'bold');
  pdf.text('Item', 14, y);
  pdf.text('Qty', 110, y);
  pdf.text('Unit', 130, y);
  pdf.text('Total', 160, y);
  y += 4;
  pdf.line(14, y, 196, y);
  y += 5;
  pdf.setFont('helvetica', 'normal');
  for (const it of items) {
    const name = String(it.name || '').slice(0, 40);
    const qty = Number(it.qty || 1);
    const unit = Number(it.unit ?? it.price ?? 0);
    const lineTotal = Number(it.price ?? 0);
    pdf.text(name, 14, y);
    pdf.text(String(qty), 110, y);
    pdf.text(unit.toLocaleString(), 130, y);
    pdf.text(lineTotal.toLocaleString(), 160, y);
    y += 6;
    if (y > 270) { pdf.addPage(); y = 18; }
  }
  y += 2;
  pdf.line(14, y, 196, y);
  y += 6;
  pdf.setFont('helvetica', 'bold');
  pdf.text(`TOTAL: KES ${Number(total).toLocaleString()}`, 14, y);
  y += 10;
  pdf.setFont('helvetica', 'italic');
  pdf.setFontSize(9);
  pdf.text('Generated by PlugPay — the trust layer for Kenya WhatsApp commerce.', 14, y);

  const filename = `${kind.toLowerCase()}-${code || 'doc'}.pdf`;
  pdf.save(filename);
}